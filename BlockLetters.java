public class BlockLetters {
    public static void main(String[] args) {
        System.out.print("L   ");
        System.out.print("    A ");
        System.out.println("     SS");
        System.out.print("L   ");
        System.out.print("   A A");
        System.out.println("   SSS");
        System.out.print("L   ");
        System.out.print("  AAAAA");
        System.out.println("   S");
        System.out.print("L   ");
        System.out.print(" A     A");
        System.out.println("  SSS");
        System.out.print("LLLL");
        System.out.print(" A     A");
        System.out.println(" SSS");
    }
}
